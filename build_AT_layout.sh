#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")"

MAIN_FILE=".AT Translated Set 2 keyboard.toml"

# Build Layout 0
if [ -f ".AT Translated Set 2 keyboard::0.toml" ] && [ -f "$MAIN_FILE" ]; then
    python3 -c '
with open(".AT Translated Set 2 keyboard.toml", "r") as f:
    template = f.read()

with open(".AT Translated Set 2 keyboard::0.toml", "r") as f:
    sub_content = f.read()

# Replace layout title and add generation comment
output = template.replace("#<layout_title>", "#Layout 0\n#This file is generated by running the `build_at_layout.sh`")

# If the layout-specific file contains section headers, handle them properly or place them accordingly.
# Since the layout-specific files have [remap] and [commands], let us extract or handle them:
# Or if #<layout_custom_remap> is still present, we replace it. Let us adjust template handling to support [remap] and [commands] inside subfiles.

# Let us parse sub_content for [remap] and [commands] sections if present.
import re

remap_match = re.search(r"\[remap\](.*?)(?=\[commands\]|$)", sub_content, re.DOTALL)
commands_match = re.search(r"\[commands\](.*)", sub_content, re.DOTALL)

remap_text = remap_match.group(1).strip() if remap_match else ""
commands_text = commands_match.group(1).strip() if commands_match else ""

# If explicit placeholders exist:
output = output.replace("#<layout_custom_remap>", remap_text)
output = output.replace("#<layout_custom_commands>", commands_text)

with open("AT Translated Set 2 keyboard::0.toml", "w") as f:
    f.write(output)
'
    echo "Generated AT Translated Set 2 keyboard::0.toml"
fi

# Build Layout 1
if [ -f ".AT Translated Set 2 keyboard::1.toml" ] && [ -f "$MAIN_FILE" ]; then
    python3 -c '
import re

with open(".AT Translated Set 2 keyboard.toml", "r") as f:
    template = f.read()

with open(".AT Translated Set 2 keyboard::1.toml", "r") as f:
    sub_content = f.read()

output = template.replace("#<layout_title>", "#Layout 1\n#This file is generated by running the `build_at_layout.sh`")

remap_match = re.search(r"\[remap\](.*?)(?=\[commands\]|$)", sub_content, re.DOTALL)
commands_match = re.search(r"\[commands\](.*)", sub_content, re.DOTALL)

remap_text = remap_match.group(1).strip() if remap_match else ""
commands_text = commands_match.group(1).strip() if commands_match else ""

output = output.replace("#<layout_custom_remap>", remap_text)
output = output.replace("#<layout_custom_commands>", commands_text)

with open("AT Translated Set 2 keyboard::1.toml", "w") as f:
    f.write(output)
'
    echo "Generated AT Translated Set 2 keyboard::1.toml"
fi
